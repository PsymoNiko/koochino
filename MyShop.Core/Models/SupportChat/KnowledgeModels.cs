using System;
using System.Collections.Generic;

namespace MyShop.Core.Models.SupportChat
{
    public static class KnowledgeArticleStatuses
    {
        public const string Draft = "Draft";
        public const string Published = "Published";
        public const string Archived = "Archived";
    }

    public static class KnowledgeArticleTypes
    {
        public const string Article = "Article";
        public const string Faq = "Faq";
    }

    /// <summary>Who an article is written for. Mirrors <c>MyShop.Core.Models.Ai.AiAudience</c>.</summary>
    public static class KnowledgeAudiences
    {
        public const string Customer = "Customer";
        public const string StoreOwner = "StoreOwner";
        public const string Both = "Both";
    }

    public class KnowledgeCategory
    {
        public int Id { get; set; }
        public int? SiteId { get; set; }
        public string Name { get; set; }
        public string Slug { get; set; }
        public string Description { get; set; }
        public int SortOrder { get; set; }
        public bool IsActive { get; set; } = true;
        public DateTime CreatedAt { get; set; }
        public int ArticleCount { get; set; }
    }

    public class KnowledgeArticle
    {
        public int Id { get; set; }
        public int? SiteId { get; set; }
        public int? CategoryId { get; set; }
        public string CategoryName { get; set; }
        public string Title { get; set; }
        public string Slug { get; set; }
        public string Summary { get; set; }
        public string Content { get; set; }
        public string ArticleType { get; set; } = KnowledgeArticleTypes.Article;
        public string Audience { get; set; } = KnowledgeAudiences.Both;

        /// <summary>Set for articles generated by an importer or the AI draft pipeline, so re-runs update instead of duplicating.</summary>
        public string SourceKey { get; set; }

        /// <summary>When set, this draft was mined from a closed live-chat conversation.</summary>
        public Guid? SourceChatId { get; set; }
        public string CoverImageUrl { get; set; }
        public string Status { get; set; } = KnowledgeArticleStatuses.Draft;
        public bool IsPublic { get; set; } = true;
        public int? AuthorUserId { get; set; }
        public DateTime? PublishedAt { get; set; }
        public string SeoTitle { get; set; }
        public string SeoDescription { get; set; }
        public DateTime CreatedAt { get; set; }
        public DateTime UpdatedAt { get; set; }
        public List<string> Tags { get; set; } = new();
    }

    public class KnowledgeTag
    {
        public int Id { get; set; }
        public int? SiteId { get; set; }
        public string Name { get; set; }
    }
}
